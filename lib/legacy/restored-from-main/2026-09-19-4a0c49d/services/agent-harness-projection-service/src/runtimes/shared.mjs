import { canonical } from "@red-cup-engineering/computer-data-engine/json";

/**
 * Rendering shared by every runtime parameterization: hook grouping, the role
 * body from a seated office, skill trees, and the manifest file. A runtime
 * module supplies only its surface (which paths, which codec) and its
 * command shapes.
 */

/** Bind the one machine-dependent token a policy may carry: `{{root}}` in an environment value becomes the repository root. */
export function bindRoot(root, environment) {
  return Object.fromEntries(Object.keys(environment).sort().map((key) => [key, environment[key].replaceAll("{{root}}", root)]));
}

/** Canonical JSON text (RFC 8785) with one trailing newline: the one JSON carrier form this package writes. */
export function jsonText(value) {
  return `${canonical(value)}\n`;
}

/** Group policy hooks by event and matcher, rendering each handler through the runtime's command shape. */
export function groupHooks(hooks, command) {
  const events = {};
  for (const hook of hooks) {
    const groups = events[hook.event] ?? (events[hook.event] = []);
    const matcher = hook.matcher ?? null;
    let group = groups.find((candidate) => (candidate.matcher ?? null) === matcher);
    if (!group) {
      group = matcher === null ? { hooks: [] } : { matcher, hooks: [] };
      groups.push(group);
    }
    group.hooks.push(command(hook));
  }
  return events;
}

const list = (value) => (Array.isArray(value) ? value.filter((item) => typeof item === "string") : []);
const dutyName = (duty) => duty.split("/").at(-1);

/** One sentence naming the office for a runtime's delegation description. */
export function roleDescription(role) {
  const office = role.office;
  if (typeof office.description === "string" && office.description.length > 0) return office.description;
  const structure = typeof office["normative-structure"] === "string" ? office["normative-structure"] : "";
  const sentence = structure.split(/(?<=[.!?])\s/u)[0] ?? "";
  return sentence.length > 0 ? sentence : `${office.name ?? role.id}: a seated office of the enterprise.`;
}

/** The instruction body for a seated role: the office, its deontic profile, its duties, and the skills it provides. */
export function roleBody(role, skills) {
  const office = role.office;
  const provided = list(office["provides-skill"]);
  const installed = skills.filter((skill) => provided.includes(skill.name));
  const deontic = office["deontic-profile"] && typeof office["deontic-profile"] === "object" ? Object.entries(office["deontic-profile"]) : [];
  const duties = list(office["bears-duty"]).map(dutyName);
  const parts = [
    `# ${office.name ?? role.id}`,
    "",
    "Generated by the agent-harness projection from the seated office record; edits here are discarded on the next projection.",
    "",
    `Seated by incumbency ${role.incumbency.id} for character ${role.character.id}.`,
    "",
    "## The office",
    "",
    typeof office["normative-structure"] === "string" ? office["normative-structure"] : "",
  ];
  if (deontic.length > 0) parts.push("", "## Deontic profile", "", ...deontic.map(([duty, stance]) => `- ${duty.replaceAll("-", " ")}: ${stance}`));
  if (duties.length > 0) parts.push("", "## Duties", "", ...duties.map((duty) => `- ${duty}`));
  if (provided.length > 0) {
    parts.push("", "## Skills", "", "The office's skills follow in full; there is nothing to invoke. Scripts a skill names run from the repository root.");
    for (const skill of installed) parts.push("", `### ${skill.name}`, "", skill.texts["SKILL.md"].trim());
    const missing = provided.filter((name) => !installed.some((skill) => skill.name === name));
    if (missing.length > 0) parts.push("", `Declared but not projected here: ${missing.join(", ")}.`);
  }
  return `${parts.join("\n").trimEnd()}\n`;
}

/** Every file of every skill, placed beneath the runtime's skills directory. */
export function skillFiles(skills, skillsDirectory) {
  const files = [];
  for (const skill of skills) for (const file of skill.files) files.push({ path: `${skillsDirectory}/${skill.name}/${file}`, text: skill.texts[file] });
  return files;
}

/** The manifest the write effect prunes against: every path this projection owns, and the actor and runtime that own it. */
export function manifestFile(path, { actor, runtime, files }) {
  return { path, text: jsonText({ kind: "agent-harness-manifest", version: 1, actor, runtime, files: files.map((file) => file.path).sort() }) };
}
