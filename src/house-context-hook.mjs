#!/usr/bin/env node
/**
 * @module house-context-hook
 * The carrier that brings the 561 Group's rules, Leader decisions and open work into every Claude Code
 * session started in the Group's working trees (rule capitalized-leader-statements-mark-a-failed-carrier;
 * requirement the-session-charge-is-delivered-by-the-harness). One zero-dependency command serves three events,
 * told apart by the payload's `hook_event_name`:
 *
 *   SessionStart     the projection: binding rules, standing decisions, open carriers, the checklist.
 *   SubagentStart    the shorter projection, because a sub-agent does not receive SessionStart context.
 *   UserPromptSubmit the carrier-repair instruction, when the prompt is a capitalized Leader statement.
 *
 *   house-context-hook --tree <working tree>... [--section <561-group-services-section dir>] [--offline]
 *
 * It exits 0 and prints at most one JSON document; a session outside the named trees, or a prompt that is not
 * in capitals, gets nothing. Failure is stated in the context ("could not be projected"), never hidden: a
 * session that starts without the house has itself a carrier to repair. The text is generated by
 * `house-context.mjs` from the section's records, never written here.
 */
import { realpathSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { hookOutput, projectHouseContext, HOOK_FILE } from "./house-context.mjs";
import { shellQuote } from "./host-resource-hook.mjs";

const SOURCE = fileURLToPath(import.meta.url);
export const EVENTS = Object.freeze(["SessionStart", "SubagentStart", "UserPromptSubmit"]);
export { HOOK_FILE };

/** `--tree <dir>` (repeatable), `--section <dir>`, `--offline`, `--event <name>` (for a manual run). */
export function parseArguments(argv) {
  const options = { trees: [], section: undefined, offline: false, liveCarriers: false, event: undefined };
  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index];
    if (flag === "--offline") { options.offline = true; continue; }
    if (flag === "--live-carriers") { options.liveCarriers = true; continue; }
    const value = argv[index + 1];
    if (!["--tree", "--section", "--event"].includes(flag) || value === undefined) throw new TypeError(`house-context-hook: expected --tree, --section, --event or --offline at ${flag}`);
    if (flag === "--tree") options.trees.push(value);
    else if (flag === "--section") options.section = value;
    else options.event = value;
    index += 1;
  }
  if (options.trees.length === 0 && options.section === undefined) throw new TypeError("house-context-hook: name at least one --tree (or a --section)");
  return Object.freeze(options);
}

/** One hook group per event, each running this source with the same arguments. */
export function houseContextHookEntries(hookArguments, { node = process.execPath, source = SOURCE, timeout = 20 } = {}) {
  parseArguments(hookArguments);
  const command = [node, source, ...hookArguments].map(shellQuote).join(" ");
  const group = () => ({ hooks: [{ type: "command", command, timeout }] });
  return Object.freeze({ SessionStart: [group()], SubagentStart: [group()], UserPromptSubmit: [group()] });
}

/** Settings hooks with the entries in place: unrelated hooks are kept, any earlier entry of this hook is replaced. */
export function mergeHouseContextHooks(existing = {}, entries) {
  const hooks = { ...existing };
  for (const event of EVENTS) {
    hooks[event] = (hooks[event] ?? []).flatMap((group) => {
      const held = (group.hooks ?? []).filter((handler) => !String(handler.command ?? "").includes(HOOK_FILE));
      return held.length === 0 ? [] : [{ ...group, hooks: held }];
    });
    hooks[event].push(...(entries[event] ?? []));
  }
  return hooks;
}

const readAll = async (stream) => { let text = ""; for await (const chunk of stream) text += chunk; return text; };

/** The hook: always exits 0. */
export async function main(argv = process.argv.slice(2), { stdin = process.stdin, stdout = process.stdout, environment = process.env } = {}) {
  let payload = {};
  try { payload = JSON.parse(await readAll(stdin) || "{}"); } catch { payload = {}; }
  try {
    const options = parseArguments(argv);
    const event = payload.hook_event_name ?? options.event;
    if (!EVENTS.includes(event)) return;
    const text = await projectHouseContext({
      event, cwd: payload.cwd ?? process.cwd(), prompt: payload.prompt, trees: options.trees, section: options.section,
      offline: options.offline, liveCarriers: options.liveCarriers, scriptPath: path.resolve(path.dirname(SOURCE), "..", "scripts", "project-house-context.mjs"),
    });
    if (text) stdout.write(hookOutput(event, text));
  } catch (error) {
    const event = payload.hook_event_name;
    if (EVENTS.includes(event) && event !== "UserPromptSubmit") stdout.write(hookOutput(event, `HOUSE CONTEXT hook failed (${String(error?.message ?? error).slice(0, 200)}). This is a failed carrier. The current request remains the work; recover only the missing prerequisite needed for it. A projection failure does not authorize a backlog, archive or campaign survey.`));
  }
}

let invoked = false;
try { invoked = process.argv[1] !== undefined && realpathSync(process.argv[1]) === realpathSync(SOURCE); } catch { invoked = false; }
if (invoked) await main();
